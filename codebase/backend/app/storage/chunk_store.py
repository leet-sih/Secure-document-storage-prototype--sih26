# ──────────────────────────────────────────────────────────────────
# Public API
# ──────────────────────────────────────────────────────────────────

def put_chunk(storage_key: str, data: bytes) -> None:
    """Write one ciphertext chunk under the given opaque storage_key.
    storage_key must be generated by the caller (secrets.token_hex(16)).
    data must be AES-256-GCM ciphertext (tag included) — never plaintext.
    """
    if _backend() == "local":
        return _put_local(storage_key, data)
    if _backend() == "sftp":
        return _put_sftp(storage_key, data)
    raise ValueError(f"unknown chunk store backend: {_backend()!r}")


def get_chunk(storage_key: str) -> bytes:
    """Read one ciphertext chunk. Raises FileNotFoundError if the key is missing."""
    if _backend() == "local":
        return _get_local(storage_key)
    if _backend() == "sftp":
        return _get_sftp(storage_key)
    raise ValueError(f"unknown chunk store backend: {_backend()!r}")


def delete_chunks(storage_keys: list[str]) -> None:
    """Delete exactly the chunks identified by storage_keys.
    Keys come from the DB (document_chunks.storage_key), never from a directory glob.
    Idempotent — missing keys are silently ignored.
    """
    if _backend() == "local":
        return _delete_local(storage_keys)
    if _backend() == "sftp":
        return _delete_sftp(storage_keys)
    raise ValueError(f"unknown chunk store backend: {_backend()!r}")
